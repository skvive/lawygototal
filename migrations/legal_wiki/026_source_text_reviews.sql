-- Global official source text review audit; no credentials or automatic approval.
CREATE TABLE legal_wiki.source_text_reviews (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 payload_id bigint NOT NULL REFERENCES legal_wiki.canonical_imports(payload_id),
 tenant text NOT NULL,
 reviewer_id text NOT NULL,
 snapshot_sha256 text NOT NULL CHECK(snapshot_sha256 ~ '^[0-9a-f]{64}$'),
 notes text NOT NULL CHECK(length(btrim(notes)) BETWEEN 10 AND 2000),
 reviewed_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(payload_id,snapshot_sha256,tenant,reviewer_id)
);
